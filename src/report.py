class Numbers:
    """Collects \\newcommand{\\name}{value} % source lines. Names are letters only (TeX macro names); each is
    defined once, so a number has exactly one value and one documented source."""

    def __init__(self):
        self.rows, self.sections = [], []

    def section(self, title):
        self.rows.append(("", "", title))

    def add(self, name, value, source):
        if not re.fullmatch(r"[A-Za-z]+", name):
            raise ValueError(f"TeX macro names are letters only: {name!r}")
        if any(n == name for n, _, _ in self.rows):
            raise ValueError(f"\\{name} is defined twice")
        self.rows.append((name, str(value), source))

    def names(self):
        return {n for n, _, _ in self.rows if n}

    def text(self):
        out = ["% numbers.tex -- generated by src/report.py; do not edit by hand.",
               "% Every number quoted in the paper, with the table (or code constant, or citation) it comes from.",
               "% Paths are relative to results/ unless they start with src/ or config/. Rerun src/report.py after any",
               "% pipeline stage; `python src/report.py --check-tex <main.tex>` lists numbers typed by hand.", ""]
        for name, value, source in self.rows:
            if not name:
                out += ["", f"% ---- {source} " + "-" * max(0, 100 - len(source))]
            else:
                out.append(f"\\newcommand{{\\{name}}}{{{value}}}  % {source}")
        return "\n".join(out) + "\n"


def tnum(x, digits=0, sign=False):
    """A number for LaTeX text or maths: fixed decimals, thin-space thousands for integers >= 1000, a true minus."""
    if digits == 0 and abs(round(x)) >= 1000:
        s = f"{round(x):,}".replace(",", "\\,").replace("-", "")
    else:
        s = f"{abs(x):.{digits}f}"
    if x < 0 and float(s.replace("\\,", "")) != 0:
        return f"\\ensuremath{{-{s}}}"
    return f"\\ensuremath{{+{s}}}" if sign else s


def pct(x, digits=0):
    return tnum(100 * x, digits)


