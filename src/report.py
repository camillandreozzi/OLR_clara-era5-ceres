# Digits in the document body that are not data. Each pattern is removed before the check; keep the list short.
NON_DATA = [
    r"NorSat-1", r"SHA-256", r"Mat(?:é|\\'e)rn[- ~]3/2", r"\(\d\)",  # names, enumerations (1)...(5)
    r"\d+--\d+ words",  # the abstract's length note
    r"a 1\\,\\% change",  # the 'per 1 %' of a relative slope
    r"24\s*(?:\\,|~)?\s*h(?:ours)?\b",  # '24 h' / '24 hours': the daily mean, a name rather than a number
    r"lag-1\b",  # the lag-one statistic
]
SKIP_ARGS = ("label", "ref", "cref", "Cref", "eqref", "cite", "citep", "citet", "includegraphics", "input", "url",
             "bibliography", "bibliographystyle", "graphicspath", "begin", "end", "setlength", "vspace", "hspace",
             "multicolumn", "cmidrule", "newcommand", "renewcommand")


DISPLAY_MATH = r"equation|gather|align|multline"


def check_tex(path):
    """Numbers typed by hand in the body of a .tex file: any number in text; in maths, decimals and numbers >= 10
    (small integers in maths are exponents, indices and formula constants). Returns [(line, token, context)]."""
    lines = path.read_text().splitlines()
    start = next((k for k, s in enumerate(lines) if "\\begin{document}" in s), 0)
    hits, in_math = [], False
    for k in range(start, len(lines)):
        raw = lines[k]
        line = re.sub(r"(?<!\\)%.*", "", raw)
        opens = re.search(rf"\\begin\{{({DISPLAY_MATH})\*?\}}", line)
        closes = re.search(rf"\\end\{{({DISPLAY_MATH})\*?\}}", line)
        for pat in NON_DATA:
            line = re.sub(pat, " ", line)
        for cmd in SKIP_ARGS:
            line = re.sub(rf"\\{cmd}\*?(\[[^\]]*\])?(\([^)]*\))?\{{[^{{}}]*\}}(\{{[^{{}}]*\}})?", " ", line)
        line = re.sub(r"\\\\\[[^\]]*\]", " ", line)  # \\[4pt]
        line = re.sub(r"\[?\d*\.?\d+\\?(pt|cm|mm|em|ex|in|textwidth|columnwidth|linewidth|textheight)\b\]?", " ",
                      line)
        if opens or in_math:
            line = "$" + line.replace("$", " ") + "$"
        in_math = (in_math or bool(opens)) and not closes
        hits += [(k + 1, tok, raw.strip()[:120]) for tok in _numbers_in(line)]
    return hits


def siunitx_unsafe(path, numbers_path):
    """Number macros used inside \\SI{...}, \\clara{...} or \\flux{...} whose value is not a plain number
    (signs via \\ensuremath, thin-space groups): siunitx cannot parse them."""
    vals = dict(re.findall(r"\\newcommand\{\\([A-Za-z]+)\}\{(.*)\}  %", numbers_path.read_text()))
    used = re.findall(r"\\(?:SI|clara|flux)\{\\([A-Za-z]+)\}", path.read_text())
    return sorted({n for n in used if n in vals and not re.fullmatch(r"[0-9.]+", vals[n])})


CAMEL_LATEX = {"lVert", "rVert", "mathbb", "mathrm", "mathcal", "mathbf", "operatorname", "textbf"}


def undefined_macros(path, numbers_path):
    """camelCase macros (the numbers.tex naming, e.g. \\nObs) used in TEX but defined neither in numbers.tex nor
    in TEX itself: a misspelt number macro fails as silently as a typed number."""
    text = re.sub(r"(?<!\\)%.*", "", path.read_text())
    defined = set(re.findall(r"\\newcommand\{\\([A-Za-z]+)\}", text))
    if numbers_path.exists():
        defined |= set(re.findall(r"\\newcommand\{\\([A-Za-z]+)\}", numbers_path.read_text()))
    used = set(re.findall(r"\\([a-z]+[A-Z][A-Za-z]*)", text))
    return sorted(used - defined - CAMEL_LATEX)


def _numbers_in(line):
    """Number tokens of one line: every number in text; decimals and >= 10 inside $...$ (exponents dropped)."""
    out = []
    parts = re.split(r"(\$[^$]*\$)", line)
    for part in parts:
        is_math = part.startswith("$") and part.endswith("$") and len(part) > 1
        s = part
        if is_math:
            s = re.sub(r"[_^](\{[^{}]*\}|\\?[A-Za-z0-9])", " ", s)
            s = re.sub(r"\\mathbf\{1\}", " ", s)
        for m in re.finditer(r"(?<![A-Za-z0-9.\\])\d+(?:\.\d+)?(?![A-Za-z0-9])", s):
            tok = m.group(0)
            if is_math and "." not in tok and int(tok) < 10:
                continue
            out.append(tok)
    return out


